-- =====================================================================
-- Garrafeira — Schema DDL (schema `garrafeira`)
-- Mesmo projeto Supabase do Goals/FestasBV/SplitBill
-- (diogoandrefsilva-personalapps-database), schema isolado — não mexe em
-- nada do que já lá está.
--
-- Correr no SQL Editor do Supabase, por esta ordem:
--   schema.sql -> functions.sql -> policies.sql
-- Ver db/README.md para os passos manuais (expor o schema na API, etc).
--
-- NOTA sobre IDs: cada mutação da app é um POST/PATCH/DELETE de UMA linha
-- (não há "gravar tudo em bloco"), por isso os `id` são
-- `GENERATED BY DEFAULT AS IDENTITY` e a app lê-os de volta da resposta do
-- POST (`Prefer: return=representation`) — nunca os inventa.
--
-- NOTA sobre o modelo: um VINHO (a referência: nome, ano, produtor, castas,
-- o que a IA descobriu) é uma coisa; uma GARRAFA (a coisa física, que está
-- num lugar e que se bebe um dia) é outra. Duas garrafas do mesmo vinho em
-- prateleiras diferentes são duas linhas em `garrafas` e UMA em `vinhos` —
-- é isso que evita ter a mesma ficha da IA copiada duas vezes, e é isso que
-- deixa "consumir" dar saída a uma garrafa sem apagar o que se sabe do vinho.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS garrafeira;

-- A `service_role` (a Edge Function `vinho-info`) NÃO tem acesso a schemas
-- fora de `public` só por ser service_role — o bypass de RLS é sobre
-- policies, não sobre GRANTs. Sem isto, qualquer pedido feito com a
-- service_role key contra `garrafeira.*` falha com "permission denied for
-- schema garrafeira" (42501), silenciosamente do lado de quem chama. Foi
-- exatamente isso que fez as notificações push do Goals parecerem enviadas
-- sem nunca lá chegarem — GRANT explícito, sempre.
GRANT USAGE ON SCHEMA garrafeira TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA garrafeira TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA garrafeira TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA garrafeira GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA garrafeira GRANT USAGE, SELECT ON SEQUENCES TO service_role;

-- ---------------------------------------------------------------------
-- Controlo de acesso
-- ---------------------------------------------------------------------

-- `pode_editar` é o meio-termo que o Goals não tem: lá, quem não é admin é
-- só leitura. Aqui uma garrafeira é de casa — faz sentido que mais do que
-- uma pessoa possa dar saída a uma garrafa sem por isso poder mexer em
-- quem tem acesso à app. Admin = manda em tudo, inclusive nesta tabela;
-- editor = mexe em vinhos/garrafas/locais; o resto vê e procura.
CREATE TABLE IF NOT EXISTS garrafeira.allowed_users (
  email       text NOT NULL,
  nome        text NOT NULL DEFAULT '',
  pode_editar boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT allowed_users_pkey PRIMARY KEY (email)
);

CREATE TABLE IF NOT EXISTS garrafeira.access_requests (
  email        text NOT NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT access_requests_pkey PRIMARY KEY (email)
);

